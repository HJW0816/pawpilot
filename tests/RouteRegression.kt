import com.estareng.pawpilot.navigation.*
import com.estareng.pawpilot.vehicle.VehicleUx

fun main() {
    val stops = listOf("매송(목포)", "매송(서울)", "남한강").map { PetRestStop(it, emptyList()) }
    check(guidanceMatches(stops, listOf("매송휴게소(목포방향)")).map { it.name } == listOf("매송(목포)"))
    check(guidanceMatches(stops, listOf("매송휴게소" )).isEmpty())
    check(guidanceMatches(stops, listOf("남한강휴게소")).isEmpty())
    check(guidanceMatches(stops, emptyList()).isEmpty())
    check(routeStopCandidates(stops, listOf("매송휴게소")).let { it.size == 2 && it.none { c -> c.directionConfirmed } })
    check(routeStopCandidates(stops, listOf("매송휴게소(목포방향)")).single().stop.name == "매송(목포)")
    check(routeStopCandidates(stops, listOf("매송휴게소", "매송휴게소")).size == 2)
    check(routeStopCandidates(stops, listOf("남한강휴게소")).single().directionConfirmed == false)
    check(routeStopCandidates(stops, listOf("구매송휴게소")).isEmpty())
    check(guidanceMatches(stops, listOf("구매송휴게소(목포방향)")).isEmpty())
    check(guidanceMatches(stops, listOf("매송휴게소 목포로 이동")).isEmpty())
    check(guidanceMatches(stops, listOf("매송휴게소(서울방향), 목포 목적지")).single().name == "매송(서울)")
    check(guidanceMatches(stops, listOf("매송 휴게소（목포 방향）")).single().name == "매송(목포)")
    val destination = NaviPlace("목적지", 37.0, 127.0, "destination", "0", "native", "")
    val target = NaviPlace("휴게소", 36.0, 127.0, "stop", "0", "native", "")
    val route = RouteContext(connected = true, loading = false, guiding = true,
        destination = destination, waypointInfoReceived = true)
    check(canAppendStop(route, route.key, target))
    check(!canAppendStop(route.copy(connected = false), route.key, target))
    check(!canAppendStop(route.copy(loading = true), route.key, target))
    check(!canAppendStop(route.copy(guiding = false), route.key, target))
    check(!canAppendStop(route.copy(waypointInfoReceived = false), route.key, target))
    check(!canAppendStop(route, "old route", target))
    check(!canAppendStop(route, route.key, destination))
    check(!canAppendStop(route, route.key, target.copy(latitude = Double.NaN)))
    check(!canAppendStop(route, route.key, target.copy(latitude = 0.0, longitude = 0.0)))
    check(!canAppendStop(route, route.key, target.copy(poiId = "")))
    check(!canAppendStop(route, route.key, target.copy(poiSubId = null)))
    val existing = route.copy(waypoints = listOf(target))
    check(!canAppendStop(existing, existing.key, target))
    val full = route.copy(waypoints = listOf(target, target.copy(poiId = "second", latitude = 36.5)))
    check(!canAppendStop(full, full.key, target.copy(poiId = "third", latitude = 36.7)))
    check(route.key != route.copy(destination = destination.copy(provider = "other")).key)
    check(route.key != route.copy(destination = destination.copy(poiSubId = "1")).key)
    val guidance = route.copy(instructions = listOf("매송휴게소(목포방향) 300m"))
    val matched = routeStopCandidates(stops, guidance.instructions)
    val recommendationKey = recommendationRequestKey(guidance, matched, "dog-small", false)
    check(recommendationRequestKey(guidance.copy(remainingMeters = 1000, remainingSeconds = 300,
        instructions = listOf("매송휴게소(목포방향) 200m")), matched, "dog-small", false) == recommendationKey)
    check(recommendationRequestKey(guidance.copy(instructions = listOf("남한강휴게소 300m")), matched, "dog-small", false) != recommendationKey)
    check(recommendationRequestKey(guidance, matched, "dog-small", true) != recommendationKey)
    check(recommendationRequestKey(guidance, matched, "cat-small", false) != recommendationKey)
    check(!canAppendStop(route, route.key, target.copy(latitude = 37.0, poiId = "same-coordinate")))
    check(canAppendStop(route, route.key, target.copy(poiId = destination.poiId, provider = "other")))
    check(!VehicleUx().setupAllowed && !VehicleUx().keyboardAllowed && VehicleUx().contentLimited)
    println("PASS route: direction ambiguity, stale route, waypoint capacity, POI identity, invalid coordinates, stable recommendation key; UX: unknown restriction state fails closed")
}
